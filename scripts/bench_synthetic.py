"""Benchmark on SYNTHETIC sessions with a subject-wise dev/test split.

Subjects 0-3 were used while designing features/thresholds (dev); subjects
4..N are held out (test). These numbers measure agreement with the generator's
assumptions, NOT accuracy on real climbers. Run:

    python scripts/bench_synthetic.py --test-subjects 12
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np

from climbtrack import evaluate, report, segment, synth
from climbtrack.io import Recording


def run(subjects, kinds, fs, method):
    rows = []
    for kind in kinds:
        for sid in subjects:
            s = synth.generate_session(seed=sid, kind=kind, fs=fs)
            r = segment.segment(s.acc, s.fs, method=method)
            e = evaluate.event_scores(s.climbs, r.climbs)
            f = evaluate.frame_scores(s.climbs, r.climbs, s.t[-1])
            ious = [v for *_, v in evaluate.match_events(s.climbs, r.climbs)]
            rows.append(dict(kind=kind, subject=sid, **e, **f, ious=ious))
    return rows


def agg(rows):
    tp = sum(r["tp"] for r in rows)
    ng = sum(r["n_gt"] for r in rows)
    npd = sum(r["n_pred"] for r in rows)
    P, R = tp / max(npd, 1), tp / max(ng, 1)
    ious = [v for r in rows for v in r["ious"]]
    tow_err = [abs(r["time_on_wall_pred_s"] - r["time_on_wall_gt_s"]) / max(r["time_on_wall_gt_s"], 1) for r in rows]
    return dict(
        sessions=len(rows), climbs=ng, precision=P, recall=R, f1=2 * P * R / (P + R) if P + R else 0.0,
        mean_iou=float(np.mean(ious)) if ious else 0.0,
        count_mae=float(np.mean([abs(r["count_error"]) for r in rows])),
        exact_count=float(np.mean([r["count_error"] == 0 for r in rows])),
        frame_f1=float(np.mean([r["frame_f1"] for r in rows])),
        tow_rel_err=float(np.median(tow_err)),
        start_mae=float(np.nanmean([r["start_mae_s"] for r in rows])),
        end_mae=float(np.nanmean([r["end_mae_s"] for r in rows])),
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--test-subjects", type=int, default=12)
    ap.add_argument("--out", default="docs/bench_synthetic.md")
    a = ap.parse_args()
    dev, test = range(0, 4), range(4, 4 + a.test_subjects)
    lines = ["# Synthetic benchmark (NOT real data)", "",
             "> Generated by `scripts/bench_synthetic.py`. Ground truth comes from `climbtrack.synth`, so these "
             "numbers only say the pipeline recovers what the generator put in. Real-data validation is pending "
             "(see docs/DATA_COLLECTION.md).", "",
             "Event match: one-to-one, IoU >= 0.5. Subject-wise split: subjects 0-3 = dev (used for design), "
             f"{test.start}-{test.stop - 1} = held-out test. Each subject: 1 boulder + 1 rope session.", ""]
    hdr = "| split | method | fs | sessions | climbs | P | R | F1 | mean IoU | count MAE | exact count | frame F1 | time-on-wall rel. err (median) | start/end MAE (s) |"
    lines += [hdr, "|" + "---|" * (hdr.count("|") - 1)]
    for split, subj in (("dev", dev), ("test", test)):
        for method in ("hmm", "threshold"):
            for fs in ((50.0, 25.0) if method == "hmm" else (50.0,)):
                m = agg(run(subj, ("boulder", "rope"), fs, method))
                lines.append(
                    f"| {split} | {method} | {fs:g} | {m['sessions']} | {m['climbs']} | {m['precision']:.2f} | {m['recall']:.2f} | "
                    f"{m['f1']:.2f} | {m['mean_iou']:.2f} | {m['count_mae']:.2f} | {m['exact_count']:.0%} | {m['frame_f1']:.2f} | "
                    f"{m['tow_rel_err']:.1%} | {m['start_mae']:.1f} / {m['end_mae']:.1f} |")
                print(lines[-1], file=sys.stderr)
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    # example figure, stamped synthetic
    s = synth.generate_session(seed=test.start, kind="boulder")
    rec = Recording(s.fs, s.t, s.acc, s.gyr, source="synthetic")
    r = segment.segment(s.acc, s.fs)
    os.makedirs("docs/img", exist_ok=True)
    report.timeline_figure("docs/img/example_timeline_synthetic.png", rec.t, rec.acc, r, s.climbs,
                           title=f"synthetic boulder session, held-out subject {test.start}",
                           banner="SYNTHETIC DATA — generator output, not a real session")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
